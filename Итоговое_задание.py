from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.neural_network import MLPRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

import matplotlib.pyplot as plt
import pandas as pd

url = "https://archive.ics.uci.edu/ml/machine-learning-databases/concrete/compressive/Concrete_Data.xls"
df = pd.read_excel(url)
df.columns = ['Cement', 'Slag', 'FlyAsh', 'Water', 'Superplasticizer', 'CoarseAggregate', 'FineAggregate', 'Age', 'Strength']
print("Размер датасета (строк, столбцов):", df.shape)
print(df.isnull().sum())

"""1. Предобработка. Проверьте данные на пропуски и дубликаты, при необходимости
выполните очистку и заполните пропуски медианой. Отделите признаки (X) и цель (y = Strength).
"""

from pandas.core.dtypes.missing import isnull
if df.isnull().sum().sum() > 0:
  df = df.fillna(df.median(numeric_only=True))

df = df.drop_duplicates()

X = df.drop('Strength', axis=1)
y = df['Strength']

"""2. Масштабирование. Примените StandardScaler к всем числовым признакам."""

scaler = StandardScaler()
X_scaler = scaler.fit_transform(X)

"""3. Разбиение. Разделите данные на тренировочную (80 %) и тестовую (20 %) выборки
c фиксированным random_state.
"""

X_train, X_test, y_train, y_test = train_test_split(X_scaler, y, test_size=0.2, random_state=42)

"""4. Обучение моделей и подбор параметров (ML и Deep Learning).
Используя GridSearchCV, выполните перебор гиперпараметров для трех моделей: Случайный лес (RandomForestRegressor), Градиентный бустинг (GradientBoostingRegressor), Полносвязная нейронная сеть (MLPRegressor)
"""

models = {
    'Случайный лес': GridSearchCV(
        RandomForestRegressor(random_state=42),
        {'n_estimators': [100, 200], 'max_depth': [10, 20]},
        cv=3
    ),
    'Градиентный бустинг': GridSearchCV(
        GradientBoostingRegressor(random_state=42),
        {'n_estimators': [100, 200], 'learning_rate': [0.05, 0.1], 'max_depth': [3, 5]},
        cv=3
    ),
    'Нейронная сеть': GridSearchCV(
        MLPRegressor(max_iter=1000, random_state=42),
        {'hidden_layer_sizes': [(64, 32), (128, 64)], 'learning_rate_init': [0.001, 0.005], 'batch_size': [32, 64]},
        cv=3
    )
}
result = {}

for name, model in models.items():
  model.fit(X_train, y_train)
  print(f"Лучшие параметры ({name}): {model.best_params_}")

  y_pred = model.predict(X_test)
  mae = mean_absolute_error(y_test, y_pred)
  mse = mean_squared_error(y_test, y_pred)
  rmse = mse ** 0.5
  r2 = r2_score(y_test, y_pred)
  result[name] = {'MAE': mae, 'MSE': mse, 'RMSE': rmse, 'R2': r2}
print(result)

"""5. Оценка. На тестовой выборке вычислите для каждой модели MAE, MSE, RMSE и R-
квадрат. Постройте диаграммы рассеяния предсказанных vs фактических значений
(линия y=x для ориентира)
"""

mas_models = ['Случайный лес', 'Градиентный бустинг', 'Нейронная сеть']
fig, axes = plt.subplots(1, 3, figsize =(14, 6))
for ax, name in zip(axes, mas_models):
  model = models[name]
  y_pred = model.predict(X_test)
  ax.scatter(y_test, y_pred, alpha=0.6, s = 10)
  ax.plot([y.min(), y.max()], [y.min(), y.max()], 'r--')
  ax.set_xlabel('Фактические значения')
  ax.set_ylabel('Предсказанные модели')
  ax.set_title(f'{name}')
plt.show()

"""6. Сравнение. Составьте сводную таблицу с метриками и сделайте вывод, какая
модель лучше подходит для задачи и почему (учитывая баланс точности и
сложности модели).
"""

results_df = pd.DataFrame(result)
print("Сводная таблица метрик:")
print(results_df)

